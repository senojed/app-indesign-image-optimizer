const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.join(__dirname, '..');
const dictionary = JSON.parse(fs.readFileSync(path.join(root, 'locales/en.json'), 'utf8').replace(/^\uFEFF/, ''));
function translate(source) {
  return source.replace(/'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*"/g, token => {
    let value;
    try { value = vm.runInNewContext(token, {}, {timeout: 50}); } catch { return token; }
    return Object.hasOwn(dictionary, value) ? JSON.stringify(dictionary[value]) : token;
  });
}
function build(check = false) {
  const directory = path.join(root, 'lib/en');
  if (!check) fs.mkdirSync(directory, {recursive: true});
  const generated = [];
  for (const name of ['core', 'photoshop', 'indesign', 'ui']) {
    let source = translate(fs.readFileSync(path.join(root, 'lib', name + '.jsxinc'), 'utf8'));
    if (name === 'indesign') source = source.replaceAll("+'/lib/", "+'/lib/en/");
    if (name === 'ui') source = source.replace('+e.status+', "+(e.status==='uspech'?'success':e.status==='chyba'?'failed':e.status)+");
    generated.push([path.join(directory, name + '.jsxinc'), '// Generated by scripts/build-english.cjs; edit lib/ and locales/en.json.\n' + source]);
  }
  let entry = translate(fs.readFileSync(path.join(root, 'InDesignImageOptimizer.jsx'), 'utf8'));
  entry = entry.replaceAll('#include "lib/', '#include "lib/en/');
  generated.push([path.join(root, 'InDesignImageOptimizer.en.jsx'), entry]);
  for (const [file, content] of generated) {
    if (check) {
      if (fs.readFileSync(file, 'utf8') !== content) throw Error('Rebuild English files: ' + path.relative(root, file));
    } else fs.writeFileSync(file, content);
  }
}
module.exports = {translate, build};
if (require.main === module) { build(process.argv.includes('--check')); console.log('English build ' + (process.argv.includes('--check') ? 'verified.' : 'generated.')); }
